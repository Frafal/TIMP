// The design tokens (design/tokens.json) and the stylesheet made from them
// (css/tokens.css). Shared by tools/tokens.mjs and the tests.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./app-files.mjs";

export const TOKENS_FILE = join(ROOT, "design", "tokens.json");
export const TOKENS_CSS = join(ROOT, "css", "tokens.css");

export function readTokens(file = TOKENS_FILE){
  return JSON.parse(readFileSync(file, "utf8"));
}

/** The values of a group, without its "$description" and the like. */
export function values(group){
  return Object.fromEntries(Object.entries(group).filter(([k]) => !k.startsWith("$")).map(([k, v]) => [k, v.$value]));
}

const family = list => list.map(f => /^[\w-]+$/.test(f) && !/^(Inter|Roboto|Menlo)$/.test(f) ? f : JSON.stringify(f)).join(",");
const bezier = b => `cubic-bezier(${b.join(",")})`;

// Inter, kept with the app (css/fonts): nothing is asked of anyone at startup, and it
// works offline. The Latin letters first; the extended ones only if a text needs them.
const FONT_FACES = `@font-face{font-family:"Inter";font-style:normal;font-weight:400 700;font-display:swap;src:url(fonts/inter-latin.woff2) format("woff2");unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}
@font-face{font-family:"Inter";font-style:normal;font-weight:400 700;font-display:swap;src:url(fonts/inter-latin-ext.woff2) format("woff2");unicode-range:U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C4,U+2113,U+2C60-2C7F,U+A720-A7FF}`;

function themeVars(colors, cities){
  return [
    ...Object.entries(colors).map(([k, v]) => `--${k}:${v};`),
    ...cities.map((c, i) => `--p${i}:${c};`)
  ].join(" ");
}

/** The stylesheet, as css/tokens.css must be. */
export function tokensCss(t = readTokens()){
  const light = values(t.color.light), dark = values(t.color.dark);
  const lightCities = t.city.light.$value, darkCities = t.city.dark.$value;
  const place = values(t.place), text = values(t.text), space = values(t.space);
  const radius = values(t.radius), size = values(t.size), motion = values(t.motion), font = values(t.font);
  const always = [
    ...Object.entries(values(t.brand)).map(([k, v]) => `--brand-${k}:${v};`),
    ...Object.entries(place).map(([k, v]) => `--t-${k}:${v};`),
    ...lightCities.map((c, i) => `--map-p${i}:${c};`),
    ...Object.entries(values(t.map)).map(([k, v]) => `--map-${k}:${v};`),
    ...Object.entries(text).map(([k, v]) => `--fs-${k}:${v};`),
    ...Object.entries(space).map(([k, v]) => `--sp-${k}:${v};`),
    // R17: named by what they separate, on the scale above.
    ...Object.entries(values(t.gap)).map(([k, v]) => `--gap-${k}:${String(v).replace(/^\{space\.(\d+)\}$/, "var(--sp-$1)")};`),
    ...Object.entries(radius).map(([k, v]) => `--r-${k}:${v};`),
    `--line-w:${t.stroke.line.$value};`,
    ...Object.entries(size).map(([k, v]) => `--${k}:${v};`),
    `--dur-state:${motion.state}; --dur-expand:${motion.expand}; --dur-enter:${motion.enter}; --ease:${bezier(motion.ease)};`,
    `--f-body:${family(font.body)}; --f-display:${family(font.display)}; --f-mono:${family(font.mono)};`
  ].join("\n  ");
  return `/* Generated by tools/tokens.mjs from design/tokens.json: never edit by hand.
   The rules that go with these values: design/README.md. */
${FONT_FACES}
:root{
  ${always}
  ${themeVars(light, lightCities)}
  color-scheme:light;
}
/* Dark: when the phone is dark and no theme was chosen, or when "dark" was chosen. */
@media (prefers-color-scheme: dark){
  :root:not([data-theme="light"]){ ${themeVars(dark, darkCities)} color-scheme:dark; }
}
:root[data-theme="dark"]{ ${themeVars(dark, darkCities)} color-scheme:dark; }
/* "Reduce motion": nothing moves, things only fade (R7). */
@media (prefers-reduced-motion: reduce){
  :root{ --dur-state:1ms; --dur-expand:1ms; --dur-enter:1ms; }
}
`;
}

/** WCAG 2 contrast ratio of two #rrggbb colours. */
export function contrast(a, b){
  const lum = h => {
    const c = [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16) / 255).map(v => v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
  };
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}
